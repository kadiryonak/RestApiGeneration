"""Hypothesis as a *library*: a template-generated, persistent pytest suite.

For every documented operation one property-based test is written: path/query parameters
and the JSON body are drawn from the operation's JSON Schemas with hypothesis-jsonschema,
the request is sent, and the only oracle is "no server error" (status < 500). There is no
LLM and no feedback loop, so it answers "what does the method add over schema-driven
generation" (analysis §7.1, first row). Header/cookie parameters are not generated; the
fixed headers of the service (e.g. auth) are sent with every request.

The suite reads its target from the environment (RESTGEN_BASE_URL, RESTGEN_HEADERS), so the
same file is re-run unchanged against clean services for output coverage and stability.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from restgen.baselines.base import (
    PytestSuiteTool,
    ToolRunContext,
    ToolRunResult,
    capture,
    check_pytest_exit,
    run_command,
    suite_env,
)
from restgen.config import HypothesisSettings
from restgen.openapi import OpenApiSpec, Operation

SUITE_FILE = "test_api_hypothesis.py"
HARD_TIMEOUT_MARGIN_SECONDS = 300

_TEMPLATE = '''\
"""Generated by restgen (hypothesis-pytest baseline). Do not edit by hand.

One property-based test per documented operation. Inputs are drawn from the OpenAPI
JSON Schemas with hypothesis-jsonschema; the only oracle is "no server error".
Target: RESTGEN_BASE_URL, RESTGEN_HEADERS (JSON), RESTGEN_REQUEST_TIMEOUT.
"""

import json
import os
from urllib.parse import quote

import httpx
from hypothesis import HealthCheck, Phase, given, seed, settings
from hypothesis import strategies as st
from hypothesis_jsonschema import from_schema

BASE_URL = os.environ["RESTGEN_BASE_URL"].rstrip("/")
HEADERS = json.loads(os.environ.get("RESTGEN_HEADERS", "{{}}"))
TIMEOUT = float(os.environ.get("RESTGEN_REQUEST_TIMEOUT", "10"))
BASE_PATH = {base_path!r}
SEED = {seed}
OPERATIONS = json.loads({operations!r})
SETTINGS = settings(
    max_examples={max_examples},
    deadline=None,
    database=None,
    suppress_health_check=list(HealthCheck),
    # No shrinking, as for Schemathesis (--no-shrink): budget goes to exploration.
    phases=[Phase.explicit, Phase.reuse, Phase.generate, Phase.target],
)
_STRATEGIES = {{}}


def _strip_formats(schema):
    if isinstance(schema, dict):
        return {{k: _strip_formats(v) for k, v in schema.items() if k != "format"}}
    if isinstance(schema, list):
        return [_strip_formats(v) for v in schema]
    return schema


def _strategy(schema):
    key = json.dumps(schema, sort_keys=True)
    if key not in _STRATEGIES:
        try:
            strategy = from_schema(schema)
            strategy.validate()
        except Exception:  # unsupported format or keyword: fall back without formats
            strategy = from_schema(_strip_formats(schema))
        _STRATEGIES[key] = strategy
    return _STRATEGIES[key]


def _text(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return ""
    if isinstance(value, (dict, list)):
        return json.dumps(value)
    return str(value)


def _call(data, operation):
    path = operation["path"]
    params = {{}}
    for parameter in operation["parameters"]:
        location, name = parameter["in"], parameter["name"]
        if location == "path":
            value = _text(data.draw(_strategy(parameter["schema"]), label=name))
            path = path.replace("{{" + name + "}}", quote(value, safe=""))
        elif location == "query" and (parameter["required"] or data.draw(st.booleans())):
            value = data.draw(_strategy(parameter["schema"]), label=name)
            params[name] = [_text(v) for v in value] if isinstance(value, list) else _text(value)
    extra = {{}}
    body = operation["body"]
    if body is not None and (operation["body_required"] or data.draw(st.booleans())):
        extra["json"] = data.draw(_strategy(body), label="body")
    response = httpx.request(
        operation["method"],
        BASE_URL + BASE_PATH + path,
        params=params,
        headers=HEADERS,
        timeout=TIMEOUT,
        **extra,
    )
    assert response.status_code < 500, (
        f"{{operation['method']}} {{path}} -> {{response.status_code}}: {{response.text[:200]}}"
    )
{tests}'''

_TEST = """

@SETTINGS
@seed(SEED)
@given(data=st.data())
def {name}(data):
    _call(data, OPERATIONS[{key!r}])
"""


def suite_test_name(operation: Operation, taken: set[str]) -> str:
    stem = re.sub(r"[^0-9a-zA-Z]+", "_", f"{operation.method}_{operation.path}").strip("_")
    name = f"test_{stem.lower()}"
    candidate, counter = name, 2
    while candidate in taken:
        candidate, counter = f"{name}_{counter}", counter + 1
    taken.add(candidate)
    return candidate


def render_suite(spec: OpenApiSpec, seed: int, max_examples: int) -> str:
    operations = {
        op.key: {
            "method": op.method,
            "path": op.path,
            "parameters": [
                {"name": p.name, "in": p.location, "required": p.required, "schema": p.schema}
                for p in op.parameters
            ],
            "body": op.json_body,
            "body_required": op.body_required,
        }
        for op in spec.operations
    }
    taken: set[str] = set()
    tests = "".join(
        _TEST.format(name=suite_test_name(op, taken), key=op.key) for op in spec.operations
    )
    return _TEMPLATE.format(
        base_path=spec.base_path,
        seed=seed,
        operations=json.dumps(operations, sort_keys=True),
        max_examples=max_examples,
        tests=tests,
    )


class HypothesisPytest(PytestSuiteTool):
    name = "hypothesis"

    def __init__(self, settings: HypothesisSettings, spec: OpenApiSpec) -> None:
        self._settings = settings
        self._spec = spec

    @property
    def python(self) -> Path:
        return self._settings.python

    def version(self) -> str:
        return capture(
            [
                self._python(),
                "-c",
                "import hypothesis, importlib.metadata as m; "
                'print(f"hypothesis {hypothesis.__version__}, '
                "hypothesis-jsonschema {m.version('hypothesis-jsonschema')}\")",
            ]
        )

    def generate(self, context: ToolRunContext) -> Path:
        suite = context.output_dir / "suite" / SUITE_FILE
        suite.parent.mkdir(parents=True, exist_ok=True)
        suite.write_text(
            render_suite(self._spec, context.seed, context.budget.max_examples), encoding="utf-8"
        )
        return suite

    def run(self, context: ToolRunContext) -> ToolRunResult:
        suite = self.generate(context)
        junit = context.output_dir / "junit.xml"
        argv = self.pytest_argv([suite], junit)
        exit_code, seconds = run_command(
            argv,
            context.output_dir / "tool.log",
            timeout=context.budget.max_time_seconds + HARD_TIMEOUT_MARGIN_SECONDS,
            env=suite_env(
                context.base_url, context.headers, context.budget.request_timeout_seconds
            ),
            cwd=suite.parent,
        )
        check_pytest_exit(exit_code, context.output_dir)
        return ToolRunResult(
            tool=self.name,
            version=self.version(),
            command=tuple(argv),
            exit_code=exit_code,
            wall_seconds=round(seconds, 3),
            tests=(suite,),
            reports={"junit": junit},
        )
